#!/usr/bin/env bash
# Claude Code (native installer) for the agent user.
# Login is interactive and done once by a human: from the VNC terminal run `claude` → /login
# (subscription account). Credentials stay in /home/agent/.claude.

DESCRIPTION="Claude Code (native) za korisnika agent + shell okruženje"

shell_rc() { echo "/home/$AGENT_USER/.config/social-agent/shell.sh"; }

check() {
  [[ -x "/home/$AGENT_USER/.local/bin/claude" ]] || return 1
  as_agent "/home/$AGENT_USER/.local/bin/claude --version" &>/dev/null || return 1
  [[ -f "$(shell_rc)" ]] || return 1
  grep -q 'social-agent/shell.sh' "/home/$AGENT_USER/.bashrc" || return 1
  grep -q 'social-agent/shell.sh' "/home/$AGENT_USER/.profile" || return 1
}

apply() {
  if [[ ! -x "/home/$AGENT_USER/.local/bin/claude" ]]; then
    as_agent 'curl -fsSL https://claude.ai/install.sh | bash'
  fi

  # One env file sourced by login shells (cron/scripts) and desktop terminals alike.
  local home="/home/$AGENT_USER" shrc; shrc="$(shell_rc)"
  install -d -m 700 -o "$AGENT_USER" -g "$AGENT_USER" "$home/.config/social-agent"
  {
    echo "# generated by social-agent modules/40-claude.sh"
    echo "export PATH=\"\$HOME/.local/bin:$SA_REPO/bin:\$PATH\""
    echo "export DISPLAY=\"\${DISPLAY:-:1}\""
    echo "export SA_REPO=\"$SA_REPO\""
    echo "export SA_DATA=\"$SA_DATA\""
    echo "[ -f \"\$HOME/.config/social-agent/agent.env\" ] && set -a && . \"\$HOME/.config/social-agent/agent.env\" && set +a"
  } > "$shrc"
  chown "$AGENT_USER:$AGENT_USER" "$shrc"

  local f
  for f in "$home/.profile" "$home/.bashrc"; do
    touch "$f"
    if ! grep -q 'social-agent/shell.sh' "$f"; then
      printf '\n# social-agent\n[ -f "$HOME/.config/social-agent/shell.sh" ] && . "$HOME/.config/social-agent/shell.sh"\n' >> "$f"
    fi
    chown "$AGENT_USER:$AGENT_USER" "$f"
  done

  as_agent "/home/$AGENT_USER/.local/bin/claude --version"
}
