#!/usr/bin/env bash
# Secrets file /etc/social-agent/.env — generated once, never committed.
# Missing keys are filled in on every run, existing values are never overwritten.

DESCRIPTION="tajne u /etc/social-agent/.env (generišu se jednom)"

# KEY  generator   — generator is evaluated only when the key is missing.
declare -A GEN=(
  [AGENT_USER]="echo agent"
  [AGENT_PASSWORD]="rand_alnum 20"
  [VNC_PASSWORD]="rand_alnum 8"               # VNC auth uses at most 8 chars
  [VNC_GEOMETRY]="echo 1920x1080"
  [SA_TZ]="echo Europe/Belgrade"
  [SA_DATA]="echo /srv/social-agent"
  [POSTGRES_DB]="echo social_agent"
  [POSTGRES_USER]="echo sa_admin"
  [POSTGRES_PASSWORD]="rand_alnum 32"
  [PG_AGENT_USER]="echo sa_agent"
  [PG_AGENT_PASSWORD]="rand_alnum 32"
  [GARAGE_RPC_SECRET]="rand_hex 32"
  [GARAGE_ADMIN_TOKEN]="rand_alnum 40"
  [GARAGE_CAPACITY]="echo 60G"
  [S3_ENDPOINT]="echo http://127.0.0.1:3900"
  [S3_REGION]="echo garage"
  [S3_BUCKET]="echo social-agent"
  [S3_ACCESS_KEY_ID]="echo GK\$(rand_hex 12)"   # Garage key id format: GK + 24 hex
  [S3_SECRET_ACCESS_KEY]="rand_hex 32"
  [BACKUP_RETENTION_DAYS]="echo 30"
  [GITHUB_KEYS_USER]="echo"                    # optional: also authorize github.com/<user>.keys
)
ORDER=(AGENT_USER AGENT_PASSWORD VNC_PASSWORD VNC_GEOMETRY SA_TZ SA_DATA
       POSTGRES_DB POSTGRES_USER POSTGRES_PASSWORD PG_AGENT_USER PG_AGENT_PASSWORD
       GARAGE_RPC_SECRET GARAGE_ADMIN_TOKEN GARAGE_CAPACITY
       S3_ENDPOINT S3_REGION S3_BUCKET S3_ACCESS_KEY_ID S3_SECRET_ACCESS_KEY
       BACKUP_RETENTION_DAYS GITHUB_KEYS_USER)

check() {
  [[ -f "$SA_ENV_FILE" ]] || return 1
  [[ "$(stat -c %a "$SA_ENV_FILE")" == 600 ]] || return 1
  local k
  for k in "${ORDER[@]}"; do grep -qE "^${k}=" "$SA_ENV_FILE" || return 1; done
}

apply() {
  install -d -m 700 "$(dirname "$SA_ENV_FILE")"
  if [[ ! -f "$SA_ENV_FILE" ]]; then
    printf '# social-agent secrets — generated by modules/01-env.sh on %s\n# NEVER commit this file.\n' "$(date -Is)" > "$SA_ENV_FILE"
  fi
  chmod 600 "$SA_ENV_FILE"
  local k v
  for k in "${ORDER[@]}"; do
    grep -qE "^${k}=" "$SA_ENV_FILE" && continue
    v="$(eval "${GEN[$k]}")"
    env_set "$k" "$v"
    log "generisan $k"
  done
  dim "lozinke vidiš sa: sudo cat $SA_ENV_FILE"
}
